#!/usr/bin/env python3
"""README summary: vLLM decode arms, and vLLM vs sglang decode at matched load.

    python3 gen_summary.py                       # print the markdown
    python3 gen_summary.py --write-readme        # replace the generated block in README.md

Generated, never hand-copied: every number is read from the result files.
  vLLM   results/k3v_pd2p2d_*.json + .decode.json        (this repo)
  sglang ../kimi-k3-sglang/results/k3s_pd2x2_*.json      (sibling repo, if present)

Cells are decode-side tok/s while decode was FULL (decode_sampler.py) / TPOT p50,
mean over replicates when there is more than one (the replicate count is shown).
Only like-for-like rows are used: ISL 1024 / OSL 2048, no speculative decoding,
and for sglang only the sgla6a8c560 image (the 0901-image rows are a different
software generation). deepep_v2 rows from the legacy-patch image and the PR
#61707 image are pooled: the PR run reproduced the legacy numbers within their
spread.
"""
import argparse
import json
import re
from collections import defaultdict
from pathlib import Path
from statistics import mean

HERE = Path(__file__).resolve().parent
VLLM = re.compile(
    r"k3v_pd2p2d_kv-nixl_dec-(?P<mode>[a-z_0-9]+?)(?:_sms(?P<sms>\d+))?_seqs\d+"
    r"_isl1024_osl2048_c(?P<conc>\d+)_n\d+(?:_r\d+)?(?:_img-[a-z0-9]+)?_[\d-]+\.json$")
SGL = re.compile(
    r"k3s_pd2x2_dec-(?P<attn>tp|dp|dcp)16ep16_sms(?P<sms>\d+)_specoff_cap\d+_run\d+"
    r"_isl1024_osl2048_c(?P<conc>\d+)_n\d+_r\d+_img-sgla6a8c560_[\d-]+\.json$")
BEGIN = "<!-- BEGIN generated by gen_summary.py: do not edit by hand -->"
END = "<!-- END generated by gen_summary.py -->"


def collect(root, pat, keyfn):
    out = defaultdict(list)
    if not root.is_dir():
        return out
    for p in sorted(root.glob("*.json")):
        if p.name.endswith(".decode.json"):
            continue
        m = pat.search(p.name)
        if not m:
            continue
        d = p.with_name(p.name[:-5] + ".decode.json")
        dec = json.loads(d.read_text()) if d.exists() else {}
        if dec.get("sat_gen_tok_s") is None:
            continue  # never full: not a decode-throughput number
        out[keyfn(m)].append((dec["sat_gen_tok_s"], json.loads(p.read_text())["median_tpot_ms"]))
    return out


def cell(rs, gpus=16, per_gpu=False):
    if not rs:
        return "—"
    tok = mean(t for t, _ in rs)
    tpot = mean(x for _, x in rs)
    n = f" ×{len(rs)}" if len(rs) > 1 else ""
    if per_gpu:
        return f"{tok:.0f} ({tok / gpus:.0f}/GPU) / {tpot:.1f} ms{n}"
    return f"{tok:.0f} / {tpot:.1f} ms{n}"


def rel(a, b):
    if not a or not b:
        return "—"
    return f"{mean(t for t, _ in a) / mean(t for t, _ in b) - 1:+.1%}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--vllm", default=HERE / "results", type=Path)
    ap.add_argument("--sglang", default=HERE.parent / "kimi-k3-sglang" / "results", type=Path)
    ap.add_argument("--write-readme", action="store_true")
    a = ap.parse_args()

    v = collect(a.vllm, VLLM, lambda m: (m["mode"], int(m["sms"]) if m["sms"] else None, int(m["conc"])))
    s = collect(a.sglang, SGL, lambda m: (m["attn"], int(m["sms"]), int(m["conc"])))

    L = [BEGIN, ""]
    L += ["### vLLM: four decode arms (2P2D, decode 16 × B300, prefill TP16 shared)", "",
          "decode tok/s while full / TPOT p50. DeepEP v2 and agrs are TP1 × DP16 (EP16);",
          "tp is TP16 (EP16, MoE output all-reduced; vLLM runs no a2a at DP=1).", "",
          "| conc (per GPU) | DeepEP v2, SM12 | DeepEP v2, auto (=64 SMs) | allgather_reducescatter | pure TP16 (all-reduce) |",
          "|---|---|---|---|---|"]
    for c in (256, 512, 1024):
        d12, d0 = v.get(("deepep_v2", 12, c)), v.get(("deepep_v2", 0, c))
        ag, tp = v.get(("agrs", 12, c)), v.get(("tp", 12, c))
        L.append(f"| {c} ({c // 16}) | **{cell(d12)}** | {cell(d0)} ({rel(d0, d12)}) | "
                 f"{cell(ag)} ({rel(ag, d12)}) | {cell(tp)} ({rel(tp, d12)}) |")
    L += ["", "Percentages are tok/s relative to DeepEP v2 SM12 at the same concurrency.", ""]

    if s:
        L += ["### vLLM vs sglang decode at matched per-GPU load", "",
              "Same 4 hosts, same 2P2D split, same DeepEP (amazon 6de427b), NCCL 2.31.2, GIN type 5,",
              "ISL 1024 / OSL 2048, no speculative decoding. sglang = `lmsysorg/sglang` main a6a8c560",
              "+ `kimi-k3-sglang` patches; its decode is TP16/EP16 with attention either TP16 (`tp`)",
              "or DP16 (`--enable-dp-attention`, the vLLM-equivalent layout). sglang decode tops out",
              "at 512 concurrent (DeepEP v2 CAP=512).", "",
              "| conc (per GPU) | vLLM DP16, SM12 | vLLM DP16, auto | sglang DP16 attn, SM12 | sglang DP16 attn, auto | sglang TP16 attn, SM12 |",
              "|---|---|---|---|---|---|"]
        for c in (128, 256, 512, 1024):
            row = [v.get(("deepep_v2", 12, c)), v.get(("deepep_v2", 0, c)),
                   s.get(("dp", 12, c)), s.get(("dp", 0, c)), s.get(("tp", 12, c))]
            if not any(row):
                continue
            L.append(f"| {c} ({c // 16}) | " + " | ".join(cell(r, per_gpu=True) for r in row) + " |")
        gaps = ", ".join(
            f"{rel(s.get(('tp', 12, c)), v.get(('deepep_v2', 12, c)))} -> "
            f"{rel(s.get(('dp', 12, c)), v.get(('deepep_v2', 12, c)))} at {c // 16}/GPU"
            for c in (256, 512) if s.get(("dp", 12, c)) and v.get(("deepep_v2", 12, c)))
        L += ["",
              "- **The topology, not the framework, decides most of it.** sglang vs vLLM (SM12),",
              f"  TP16 attention -> DP16 attention: {gaps}. TP16 attention pays per-layer",
              "  cross-node TP collectives; the remaining gap shrinks with load. sglang DP needs",
              "  `cutedsl_mla` decode attention (trtllm-gen MLA rejects 64 < heads < 128; K3 has 96",
              "  per rank) and mem-fraction 0.86.",
              "- **SM12 beats DeepEP's auto pick (64) in both frameworks.**",
              "- Single replicate unless marked `×n`; vLLM's replicate spread was <= 3.6%.", ""]
    L.append(END)
    md = "\n".join(L)

    if a.write_readme:
        p = HERE / "README.md"
        t = p.read_text()
        if BEGIN in t:
            t = t[:t.index(BEGIN)] + md + t[t.index(END) + len(END):]
        else:
            anchor = "## Results\n"
            assert anchor in t, "README has no '## Results' section to put the summary under"
            t = t.replace(anchor, anchor + "\n" + md + "\n", 1)
        p.write_text(t)
        print("README.md updated")
    else:
        print(md)


if __name__ == "__main__":
    main()
